import mongoose from "mongoose";

/**
 * Embedded sub-schema for a single purchased item.
 * The product's name and sku are SNAPSHOTTED so that
 * historical purchases remain readable even if the product
 * is later renamed or deleted.
 */
const purchaseItemSchema = new mongoose.Schema(
  {
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },
    // Snapshots (historical accuracy):
    name: { type: String, required: true },
    sku: { type: String, required: true },

    quantity: {
      type: Number,
      required: true,
      min: [1, "Quantity must be at least 1"],
    },

    purchasePrice: {
      type: Number,
      required: true,
      min: [0, "Purchase price cannot be negative"],
    },

    subtotal: {
      type: Number,
      required: true,
      min: [0, "Subtotal cannot be negative"],
    },
  },
  { _id: false } // no separate _id for line items
);

const purchaseSchema = new mongoose.Schema(
  {
    purchaseNumber: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      uppercase: true,
      // Generated by the controller in Stage 3 (e.g. PUR-20250115-0001)
    },

    supplier: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Supplier",
      required: [true, "Supplier is required"],
    },

    // Snapshot of supplier name at time of purchase
    supplierName: {
      type: String,
      required: true,
    },

    items: {
      type: [purchaseItemSchema],
      validate: {
        validator: (v) => Array.isArray(v) && v.length > 0,
        message: "A purchase must contain at least one item",
      },
    },

    subtotal: {
      type: Number,
      required: true,
      min: [0, "Subtotal cannot be negative"],
    },

    discount: {
      type: Number,
      default: 0,
      min: [0, "Discount cannot be negative"],
    },

    tax: {
      type: Number,
      default: 0,
      min: [0, "Tax cannot be negative"],
    },

    total: {
      type: Number,
      required: true,
      min: [0, "Total cannot be negative"],
    },

    amountPaid: {
      type: Number,
      default: 0,
      min: [0, "Amount paid cannot be negative"],
    },

    balance: {
      type: Number,
      default: 0,
      min: [0, "Balance cannot be negative"],
    },

    paymentMethod: {
      type: String,
      enum: ["cash", "card", "bank-transfer", "credit"],
      default: "cash",
    },

    // pending  → draft, NO stock effect
    // received → stock has been increased
    // cancelled→ stock increase reversed (if it had been received)
    status: {
      type: String,
      enum: ["pending", "received", "cancelled"],
      default: "pending",
    },

    // Idempotency flag: true only after stock has been increased for this purchase
    stockApplied: {
      type: Boolean,
      default: false,
    },

    // Audit trail
    cancelledAt: { type: Date, default: null },
    cancelReason: { type: String, default: "" },
  },
  { timestamps: true }
);

purchaseSchema.index({ createdAt: -1 });
purchaseSchema.index({ supplier: 1 });
purchaseSchema.index({ status: 1 });

const Purchase = mongoose.model("Purchase", purchaseSchema);

export default Purchase;