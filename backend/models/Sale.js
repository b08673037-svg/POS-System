import mongoose from "mongoose";

const saleItemSchema = new mongoose.Schema(
  {
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },
    // Snapshots — never modified after creation
    name: { type: String, required: true },
    sku: { type: String, required: true },

    quantity: {
      type: Number,
      required: true,
      min: [1, "Quantity must be at least 1"],
    },

    sellingPrice: {
      type: Number,
      required: true,
      min: [0, "Selling price cannot be negative"],
    },

    // Cost at the moment of sale — used for COGS-based profit calculation
    costPrice: {
      type: Number,
      required: true,
      min: [0, "Cost price cannot be negative"],
    },

    subtotal: {
      type: Number,
      required: true,
      min: [0, "Subtotal cannot be negative"],
    },
  },
  { _id: false }
);

const saleSchema = new mongoose.Schema(
  {
    invoiceNumber: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      uppercase: true,
      // Generated by the controller (e.g. INV-20250115-0001)
    },

    // Customer is optional (walk-in sales)
    customer: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Customer",
      default: null,
    },

    // Snapshot of customer name — either real name or "Walk-in Customer"
    customerName: {
      type: String,
      required: true,
      default: "Walk-in Customer",
    },
    customerPhone: {
      type: String,
      default: "",
    },

    items: {
      type: [saleItemSchema],
      validate: {
        validator: (v) => Array.isArray(v) && v.length > 0,
        message: "A sale must contain at least one item",
      },
    },

    subtotal: {
      type: Number,
      required: true,
      min: [0, "Subtotal cannot be negative"],
    },

    discount: {
      type: Number,
      default: 0,
      min: [0, "Discount cannot be negative"],
    },

    tax: {
      type: Number,
      default: 0,
      min: [0, "Tax cannot be negative"],
    },

    total: {
      type: Number,
      required: true,
      min: [0, "Total cannot be negative"],
    },

    amountPaid: {
      type: Number,
      default: 0,
      min: [0, "Amount paid cannot be negative"],
    },

    balance: {
      type: Number,
      default: 0,
      min: [0, "Balance cannot be negative"],
    },

    paymentMethod: {
      type: String,
      enum: ["cash", "card", "bank-transfer", "credit"],
      default: "cash",
    },

    paymentStatus: {
      type: String,
      enum: ["unpaid", "partial", "paid"],
      default: "paid",
    },

    // completed → stock has been decreased
    // cancelled → stock decrease has been reversed
    status: {
      type: String,
      enum: ["completed", "cancelled"],
      default: "completed",
    },

    // Idempotency: true once stock has been decremented for this sale
    stockApplied: {
      type: Boolean,
      default: false,
    },

    // Idempotency: true once stock has been restored on cancellation
    stockRestored: {
      type: Boolean,
      default: false,
    },

    // Audit trail
    cancelledAt: { type: Date, default: null },
    cancelReason: { type: String, default: "" },
  },
  { timestamps: true }
);

saleSchema.index({ createdAt: -1 });
saleSchema.index({ customer: 1 });
saleSchema.index({ status: 1 });
saleSchema.index({ paymentMethod: 1 });

const Sale = mongoose.model("Sale", saleSchema);

export default Sale;